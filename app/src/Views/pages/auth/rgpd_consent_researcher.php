    <div class="rgpd-section">
        <span class="rgpd-section-num">Article 04</span>
        <h2>Vos engagements</h2>
        <div class="rgpd-rights">
            <div class="rgpd-right-card">
                <strong>Confidentialité</strong>
                <p>Ne divulguer aucune donnée à une personne non habilitée.</p>
            </div>
            <div class="rgpd-right-card">
                <strong>Limitation de finalité</strong>
                <p>N'utiliser les données que pour la recherche autorisée, et rien d'autre.</p>
            </div>
            <div class="rgpd-right-card">
                <strong>Non ré-identification</strong>
                <p>Ne pas chercher à ré-identifier des sujets hors du cadre du protocole.</p>
            </div>
            <div class="rgpd-right-card">
                <strong>Sécurité</strong>
                <p>Protéger les données extraites (poste, support de stockage, accès).</p>
            </div>
            <div class="rgpd-right-card">
                <strong>Aucun usage commercial</strong>
                <p>Ne céder ni exploiter les données à des fins commerciales.</p>
            </div>
            <div class="rgpd-right-card">
                <strong>Signalement d'incident</strong>
                <p>Informer sans délai le DPO de toute violation ou perte de données.</p>
            </div>
        </div>
    </div>

    <div class="rgpd-section">
        <span class="rgpd-section-num">Article 05</span>
        <h2>Durée et révocation de l'accès</h2>
        <table class="rgpd-table">
            <tr>
                <td>Durée de l'habilitation</td>
                <td>Le temps du projet de recherche autorisé</td>
            </tr>
            <tr>
                <td>Révocation</td>
                <td>L'accès peut être retiré à tout moment par un administrateur ou le DPO</td>
            </tr>
            <tr>
                <td>Fin d'accès</td>
                <td>Suppression des extractions locales à l'issue du projet</td>
            </tr>
        </table>
    </div>

    <div class="rgpd-section">
        <span class="rgpd-section-num">Article 06</span>
        <h2>Vos propres données</h2>
        <p>
            Les seules données vous concernant traitées par la plateforme sont celles de votre
            compte (nom, prénom, e-mail, rôle, journaux d'accès), pour la seule gestion de votre
            accès — base légale : exécution du contrat (art. 6.1.b).
            <strong>Elles ne font l'objet d'aucune exploitation à des fins de recherche.</strong>
            Vous conservez vos droits d'accès, de rectification et d'effacement sur ces données.
        </p>
    </div>

