    <div class="rgpd-intro">
        En tant que <strong>chercheur habilité</strong>, vous accédez aux données collectées
        par la plateforme I-AMU afin de mener des travaux scientifiques. À ce titre, vous êtes
        une personne agissant sous l'autorité du responsable de traitement.
        <strong>Vos propres données ne sont pas exploitées à des fins de recherche</strong> :
        elles servent uniquement à la gestion de votre compte. Le présent document définit les
        conditions de votre accès et les engagements que vous prenez.
    </div>

