    <div class="rgpd-section">
        <span class="rgpd-section-num">Article 02</span>
        <h2>Nature de votre accès et base légale</h2>
        <p>
            Votre accès aux données n'est pas un consentement portant sur vos propres données :
            c'est une habilitation à traiter les données d'autrui pour le compte du responsable
            de traitement.
        </p>
        <table class="rgpd-table">
            <thead>
            <tr>
                <th>Élément</th>
                <th>Cadre</th>
            </tr>
            </thead>
            <tbody>
            <tr>
                <td>Statut</td>
                <td>Personne agissant sous l'autorité du responsable (art. 29 RGPD)</td>
            </tr>
            <tr>
                <td>Conditions d'accès</td>
                <td>Habilitation accordée après autorisation explicite d'un administrateur</td>
            </tr>
            <tr>
                <td>Finalité autorisée</td>
                <td>Recherche scientifique sur l'usage de l'IA générative (art. 89 RGPD)</td>
            </tr>
            <tr>
                <td>Base légale du traitement source</td>
                <td>Consentement des sujets (art. 6.1.a) + intérêt légitime de l'établissement</td>
            </tr>
            </tbody>
        </table>
    </div>

